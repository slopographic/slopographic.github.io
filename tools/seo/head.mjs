// The SEO head block every page gets (tools/seo/write.mjs): title, description, canonical, the language alternates
// (hreflang, x-default), Open Graph, Twitter and JSON-LD, between <!-- seo:start --> and <!-- seo:end --> after the
// charset tag. A hand-made page that keeps its own head gets the alternates alone, between <!-- seo:alt --> and
// <!-- /seo:alt --> (setAlternates). Read shared/seo/HANDOFF.md first.
//   headBlock({ title, description, url, image, jsonld, viewport, alternates }) -> [lines] (url: the page's; the block
//   names its canonical, robots.mjs canonicalFor)
//   injectHead(html, lines) / setAlternates(html, alternates) / setHtmlLang(html, L, { page })
//   validateCopy(entries, { lenient, code })   lengths (per script) and unique titles and descriptions in one language
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, SITE } from './site.mjs';
import { canonicalFor } from './robots.mjs';

export const DEFAULT_IMAGE = `${SITE}/og-share.png`;
export const OS = 'Any (runs in a web browser)';
export const AUTHOR = { '@type': 'Organization', name: 'Slopographic', url: `${SITE}/` };
/** Open Graph image: the app's shot when the file exists, else the site image. */
export const imageFor = (app) => (app.shot && existsSync(path.join(ROOT, app.shot)) ? `${SITE}/${app.shot}` : DEFAULT_IMAGE);
export const escAttr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
// One line of JSON (crawlers read it the same as indented JSON), so a page with a long ItemList stays within 300 lines.
const ldScript = (obj) => `<script type="application/ld+json">${JSON.stringify(obj).replace(/</g, '\\u003c')}</script>`;

/** The origin trial tokens (shared/agent/trial-tokens.json: WebMCP, one token per origin), all on one line. One build
 * serves both origins (main: slopographic.com, testing: slopographic.github.io); Chrome ignores a token made for
 * another origin. Static, in the first HTML, so the trial is on before any script runs. */
export const TRIAL_TOKENS = JSON.parse(readFileSync(path.join(ROOT, 'shared/agent/trial-tokens.json'), 'utf8')).tokens.filter((t) => /^[A-Za-z0-9+/=]+$/.test(t.token || ''));
const trialLine = () => (TRIAL_TOKENS.length ? [TRIAL_TOKENS.map((t) => `<meta http-equiv="origin-trial" content="${t.token}">`).join('')] : []);
// All on one line: a page with many languages still stays within the 300-line rule. An alternate points to the page's
// canonical where that is on this site (a single-app site's root); one moved to another site (an override) keeps its own
// address, so the language menu (shared/i18n/switcher.js) stays on this site.
const own = (href) => { const c = canonicalFor(href); return c.startsWith(SITE + '/') ? c : href; };
const altLine = (alternates = []) => (alternates.length ? [alternates.map(([lang, href]) => `<link rel="alternate" hreflang="${lang}" href="${own(href)}">`).join('')] : []);

export function headBlock({ title, description, url, image, jsonld, viewport, alternates }) {
  url = canonicalFor(url);   // the profile's canonical (robots.mjs): the page itself, another origin, or the root of a single-app site
  return [
    '<!-- seo:start: generated by tools/seo/write.mjs from shared/seo (the copy in shared/seo/i18n); edit the copy there -->',
    ...(viewport ? ['<meta name="viewport" content="width=device-width, initial-scale=1">'] : []),
    ...trialLine(),
    `<title>${escAttr(title)}</title>`,
    `<meta name="description" content="${escAttr(description)}">`,
    `<link rel="canonical" href="${url}">${altLine(alternates).join('')}`,   // the alternates on the same line: no page grows
    '<meta property="og:type" content="website">',
    '<meta property="og:site_name" content="Slopographic">',
    `<meta property="og:title" content="${escAttr(title)}">`,
    `<meta property="og:description" content="${escAttr(description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${image}">`,
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    '<meta name="twitter:card" content="summary_large_image">',
    `<meta name="twitter:title" content="${escAttr(title)}">`,
    `<meta name="twitter:description" content="${escAttr(description)}">`,
    `<meta name="twitter:image" content="${image}">`,
    ...jsonld.map(ldScript),
    '<!-- seo:end -->',
  ];
}

/** Puts lines after the charset tag (or the head tag). */
function afterCharset(out, block) {
  const tag = out.match(/<meta[^>]+charset[^>]*>/i);
  if (tag) { const at = tag.index + tag[0].length; return out.slice(0, at) + '\n  ' + block + out.slice(at); }
  const head = out.match(/<head[^>]*>/i);
  if (!head) throw new Error('no <head> to put the SEO block in');
  const at = head.index + head[0].length;
  return out.slice(0, at) + '\n  ' + block + out.slice(at);
}
const dropAlt = (html) => html.replace(/\n?[ \t]*<!-- seo:alt -->[\s\S]*?<!-- \/seo:alt -->/, '');

/** Removes the old SEO tags (or the previous block) and puts the new block after the charset tag. */
export function injectHead(html, lines) {
  let out = dropAlt(html.replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->\n?[ \t]*/, ''));
  out = out
    .replace(/[ \t]*<title[^>]*>[\s\S]*?<\/title>\n?/gi, '')
    .replace(/[ \t]*<meta\s+name=["']description["'][^>]*>\n?/gi, '')
    .replace(/[ \t]*<link\s+rel=["']canonical["'][^>]*>\n?/gi, '')
    .replace(/[ \t]*<meta\s+(?:property|name)=["'](?:og|twitter):[^"']*["'][^>]*>\n?/gi, '')
    .replace(/[ \t]*<script\s+type=["']application\/ld\+json["'][\s\S]*?<\/script>\n?/gi, '');
  if (!/<html[^>]*\slang=/i.test(out)) out = out.replace(/<html(\s|>)/i, '<html lang="en"$1');
  return afterCharset(out, lines.join('\n  '));
}

/** A page with its own hand-made head: the language alternates alone, in their own block (none: the block goes). */
export function setAlternates(html, alternates) {
  const out = dropAlt(html);
  if (!alternates || alternates.length < 3) return out;   // one language and x-default: nothing to point to
  return afterCharset(out, `<!-- seo:alt -->${altLine(alternates)[0]}<!-- /seo:alt -->`);
}

/** <html lang> (and dir) of a page in language L; page: also data-lang-page (the page is in that language only). */
export function setHtmlLang(html, L, { page = false } = {}) {
  return html.replace(/<html\b([^>]*)>/i, (m, attrs) => {
    let a = attrs.replace(/\s(lang|dir|data-lang-page)="[^"]*"/g, '');
    a = ` lang="${L.code}"${L.dir === 'rtl' ? ' dir="rtl"' : ''}${page ? ` data-lang-page="${L.code}"` : ''}` + a;
    return `<html${a}>`;
  });
}

/** Description lengths by script: Han, kana and Hangul say more per character than Latin, Cyrillic and the others. */
export function descLimits(code = 'en') {
  if (/^(zh|ja)(-|$)/.test(code)) return [45, 110];
  if (/^ko(-|$)/.test(code)) return [55, 130];
  return [120, 160];
}
const TITLE_MAX = 75;
// A renamed white-label build (tools/whitelabel/transform.mjs sets this marker): its copy is this site's with other words, so
// lengths move; every run of the SEO writer there (its CI, its deploy, a language pass) is lenient without SEO_LENIENT.
export const LENIENT_BUILD = /*profile:seoLenient*/false;

/** Checks the copy of one language: description lengths, titles, unique titles and descriptions. Throws on the first
 *  problem; lenient (a renamed white-label build, or SEO_LENIENT=1): lengths and repeats only warn. */
export function validateCopy(entries, { lenient = LENIENT_BUILD || process.env.SEO_LENIENT === '1', code = 'en' } = {}) {
  const titles = new Map(), descs = new Map(), [min, max] = descLimits(code);
  const bad = (m) => { if (lenient) console.warn(`seo (lenient): ${m}`); else throw new Error(m); };
  for (const [name, { title, description }] of entries) {
    const where = `${code} ${name}`;
    if (description.length < min || description.length > max) bad(`${where}: description is ${description.length} characters (need ${min} to ${max})`);
    if (!title) throw new Error(`${where}: title missing`);
    if (title.length > TITLE_MAX) bad(`${where}: title missing or too long`);
    if (titles.has(title)) bad(`${where}: title repeats ${titles.get(title)}`);
    if (descs.has(description) && descs.get(description) !== name) bad(`${where}: description repeats ${descs.get(description)}`);
    titles.set(title, name);
    descs.set(description, name);
  }
}
