#!/usr/bin/env node
// Translation tools for the apps (shared/i18n/APPS-HOWTO.md).
//   node tools/i18n/i18n.mjs extract <app id|shared> [--json] [--prose]   hard-coded English in an app's code, by file
//   node tools/i18n/i18n.mjs rank                     the apps by number of user-visible strings (for splitting work)
//   node tools/i18n/i18n.mjs --check                  the tables: every key in every shipped language, same {placeholders}
//   node tools/i18n/i18n.mjs coverage [--baseline]    writes shared/i18n/COVERAGE.md; --baseline raises the ratchet
//   node tools/i18n/i18n.mjs index <app id>           writes <app>/i18n/index.js from its folders, and tests/i18n/tables.covers.txt
//                                                    (a page kept like an app, tables.mjs pageAreas(): index settings)
//                                                    (index ui: UI_PARTS in shared/i18n/i18n.js; index biz: shared/biz/i18n/index.js)
//   node tools/i18n/i18n.mjs todo <app id> <code>     the English keys a language still lacks, as table lines to fill in
// extract lists UI-API strings (kind 'ui') by default; --prose adds the literals that only read like words.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { apps, appTables, sharedApp, sharedAreas, pageAreas, uiPartsIndex, UI_PARTS_RE, ROOT, COVERS, coversText } from './tables.mjs';
import { check } from './check.mjs';
import { hardcoded, scan, render, raise, OUT, BASELINE } from './coverage.mjs';

const [cmd, ...rest] = process.argv.slice(2);
const flag = (f) => rest.includes(f);
const arg = rest.filter((a) => !a.startsWith('--'));
const findApp = (id) => (id === 'shared' ? sharedApp() : [...apps(), ...pageAreas(), ...sharedAreas()].find((a) => a.id === id || a.ns === id || a.dir === id || a.dir === id + '/'));

/** The index.js an app's tables need: the parts of en/ and every language folder. */
export function indexSource(app) {
  const t = appTables(app);
  if (app.base) {   // a shared area: what its pages load (shared/i18n/APPS-HOWTO.md)
    const use = app.ns === 'seo' ? 'read by tools/seo (Node) to write the static SEO pages; no page loads it (shared/seo/i18n/README.md)'
      : `each page that uses ${app.dir} loads it before its own`;
    return `/* The shared ${app.ns} string tables (generated by node tools/i18n/i18n.mjs index ${app.ns}; edit the tables, not this file).\n` +
      ` * Loads English and the chosen language from ${app.base}<code>/<part>.js; ${use}. */\n` +
      `window.SlopI18n && window.SlopI18n.source({\n  ns: '${app.ns}',\n  base: ((document.currentScript || {}).src || '').replace(/[^/]*$/, ''),\n` +
      `  parts: ${JSON.stringify(Object.keys(t.byPart.en || {}).sort()).replace(/"/g, "'").replace(/,/g, ', ')},\n  langs: ${JSON.stringify(t.dirs).replace(/"/g, "'").replace(/,/g, ', ')},\n});\n`;
  }
  const parts = Object.keys(t.byPart.en || {}).sort();
  return `/* The ${app.name} string tables (generated by node tools/i18n/i18n.mjs index ${app.id}; edit the tables, not this file).\n` +
    ` * Loads English and the chosen language from ${app.dir}i18n/<code>/<part>.js (shared/i18n/APPS-HOWTO.md). */\n` +
    `window.SlopI18n && window.SlopI18n.source({\n  ns: '${app.id}',\n  base: ((document.currentScript || {}).src || '').replace(/[^/]*$/, ''),\n` +
    `  parts: ${JSON.stringify(parts).replace(/"/g, "'").replace(/,/g, ', ')},\n  langs: ${JSON.stringify(t.dirs).replace(/"/g, "'").replace(/,/g, ', ')},\n});\n`;
}

if (cmd === 'extract') {
  const app = findApp(arg[0]);
  if (!app) { console.error('No such app: ' + arg[0]); process.exit(2); }
  const found = hardcoded(app.files).filter((s) => flag('--prose') || s.kind === 'ui');
  if (flag('--json')) console.log(JSON.stringify(found, null, 1));
  else {
    let file = '';
    for (const s of found) { if (s.file !== file) { file = s.file; console.log('\n' + file); } console.log(`  ${String(s.line).padStart(4)}  ${s.kind === 'ui' ? ' ' : '?'} ${JSON.stringify(s.text)}`); }
    console.log(`\n${found.length} strings in ${new Set(found.map((s) => s.file)).size} files (${app.id}).`);
  }
} else if (cmd === 'rank') {
  const rows = apps().map((a) => ({ id: a.id, n: hardcoded(a.files).length + (appTables(a).tables.en ? appTables(a).tables.en.size : 0) })).sort((a, b) => b.n - a.n);
  rows.forEach((r, i) => console.log(`${String(i + 1).padStart(3)}. ${r.id.padEnd(14)} ${r.n}`));
  console.log(`Total ${rows.reduce((s, r) => s + r.n, 0)}; shared code ${hardcoded(sharedApp().files).length}.`);
} else if (cmd === '--check' || cmd === 'check') {
  const problems = check();
  for (const p of problems) console.log(p);
  console.log(problems.length ? `${problems.length} problems.` : 'The tables are sound.');
  process.exit(problems.length ? 1 : 0);
} else if (cmd === 'coverage') {
  const rows = scan();
  writeFileSync(path.join(ROOT, OUT), render(rows));
  writeFileSync(path.join(ROOT, COVERS), coversText());
  console.log('Wrote ' + OUT + ' and ' + COVERS);
  if (flag('--baseline')) {
    const file = path.join(ROOT, BASELINE);
    const base = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
    writeFileSync(file, JSON.stringify(raise(rows, base), null, 1) + '\n');
    console.log('Raised ' + BASELINE);
  }
} else if (cmd === 'index') {
  const app = findApp(arg[0]);
  if (!app || app.id === 'shared') { console.error('No such app: ' + arg[0]); process.exit(2); }
  if (app.id === 'ui-parts') {   // the ui parts' index is a literal in i18n.js
    const t = appTables(app), f = path.join(ROOT, 'shared/i18n/i18n.js');
    const lit = `{ parts: ${JSON.stringify(Object.keys(t.byPart.en || {}).sort())}, langs: ${JSON.stringify(t.dirs)} }`.replace(/"/g, "'").replace(/','/g, "', '");
    writeFileSync(f, readFileSync(f, 'utf8').replace(UI_PARTS_RE, '/*ui-parts*/' + lit + ';'));
  } else writeFileSync(path.join(ROOT, app.base || path.join(app.dir, 'i18n/'), 'index.js'), indexSource(app));
  writeFileSync(path.join(ROOT, COVERS), coversText());
  console.log(`Wrote the index of ${app.id} and ${COVERS}`);
} else if (cmd === 'todo') {
  const app = findApp(arg[0]);
  const t = app && appTables(app);
  if (!t || !t.tables.en) { console.error('No English tables for ' + arg[0]); process.exit(2); }
  const have = t.tables[arg[1]] || new Map();
  for (const [part, m] of Object.entries(t.byPart.en)) {
    const lines = [...m].filter(([k]) => !have.has(k) && !k.includes('#'));
    if (lines.length) { console.log(`// ${part}.js`); for (const [k, v] of lines) console.log(`    ${JSON.stringify(k).replace(/^"|"$/g, "'")}: ${JSON.stringify(v)},`); }
  }
} else {
  console.log(readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).map((l) => l.slice(3)).join('\n'));
}
