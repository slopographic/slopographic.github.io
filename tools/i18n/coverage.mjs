// Translation coverage per app and language (node tools/i18n/i18n.mjs coverage → shared/i18n/COVERAGE.md), and its
// ratchet (tests/node/i18n-coverage.baseline.json: coverage per app and language, raised with --baseline, never lowered).
// For each app: the keys in its English tables, the hard-coded English the extractor still finds in its code (scan.mjs),
// and per language the keys translated. Coverage = translated / (English keys + hard-coded strings): an app with every
// string in tables and every table translated is at 100%.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { apps, appTables, sharedApp, sharedAreas, pageAreas, sharedTables, langs, ROOT } from './tables.mjs';
import { scanJs, scanHtml } from './scan.mjs';

export const OUT = 'shared/i18n/COVERAGE.md';
export const BASELINE = 'tests/node/i18n-coverage.baseline.json';

/** The hard-coded strings in a list of files: [{ file, line, text, kind }]. */
export function hardcoded(files) {
  const out = [];
  for (const f of files) {
    const src = readFileSync(path.join(ROOT, f), 'utf8');
    for (const s of f.endsWith('.html') ? scanHtml(src) : scanJs(src)) out.push({ file: f, ...s });
  }
  return out;
}

/** One row per app (plus the shared tables): { id, name, keys, hard, langs: { code: translated } }. */
export function scan() {
  const codes = langs().map((l) => l.code);
  const rows = [];
  for (const ns of ['chrome', 'ui']) {
    const s = sharedTables(ns);
    const keys = s.tables.en ? [...s.tables.en.keys()].filter((k) => !k.includes('#')) : [];
    const row = { id: ns, name: ns === 'chrome' ? 'Shared chrome (header, switcher, footer, Settings)' : 'Shared components (shared/i18n/ui)', keys: keys.length, hard: null, langs: {} };
    for (const c of codes) row.langs[c] = s.tables[c] ? keys.filter((k) => s.tables[c].has(k)).length : 0;
    rows.push(row);
  }
  for (const area of sharedAreas()) {   // the ui parts and shared/<area>/i18n: a language without a folder reads English
    const t = appTables(area);
    const keys = t.tables.en ? [...t.tables.en.keys()].filter((k) => !k.includes('#')) : [];
    const row = { id: area.id, name: area.name, keys: keys.length, hard: null, shared: true, langs: {} };
    for (const c of codes) row.langs[c] = t.tables[c] ? keys.filter((k) => t.tables[c].has(k)).length : 0;
    rows.push(row);
  }
  const sh = sharedApp();
  rows.push({ id: 'shared', name: sh.name + ' (hard-coded, not yet in tables)', keys: 0, hard: hardcoded(sh.files).length, langs: {} });
  for (const app of [...apps(), ...pageAreas()]) {   // a page kept like an app (settings/) is ranked with them
    const t = appTables(app);
    const keys = t.tables.en ? [...t.tables.en.keys()].filter((k) => !k.includes('#')) : [];
    const row = { id: app.id, name: app.name, keys: keys.length, hard: hardcoded(app.files).length, langs: {} };
    for (const c of codes) row.langs[c] = c === 'en' ? keys.length : (t.tables[c] ? keys.filter((k) => t.tables[c].has(k)).length : 0);
    rows.push(row);
  }
  return rows;
}

const pct = (n, d) => (d ? Math.floor((100 * n) / d) : 0);
/** Coverage of one row in one language, in whole percent. */
export const coverage = (r, code) => pct(r.langs[code] || 0, r.keys + (r.hard || 0));

/** The markdown report. */
export function render(rows) {
  const codes = langs().map((l) => l.code);
  const apps = rows.filter((r) => !['chrome', 'ui', 'shared'].includes(r.id) && !r.shared);
  const ranked = apps.slice().sort((a, b) => b.keys + b.hard - (a.keys + a.hard) || a.id.localeCompare(b.id));
  const lines = [
    '# Translation coverage',
    '',
    'Generated by `node tools/i18n/i18n.mjs coverage`; do not edit by hand. Coverage of an app in a language is the keys',
    'translated in that language, out of the English keys in its tables plus the hard-coded English the extractor still',
    'finds in its code (`node tools/i18n/i18n.mjs extract <app>` lists them). The ratchet',
    '(`tests/node/i18n-coverage.baseline.json`) keeps every number here from going down. How to raise one: `APPS-HOWTO.md`.',
    '',
    '## Shared tables',
    '',
    '| Table | Keys | ' + codes.join(' | ') + ' |',
    '|---|---:|' + codes.map(() => '---:').join('|') + '|',
    ...rows.filter((r) => r.id === 'chrome' || r.id === 'ui' || r.shared).map((r) => `| ${r.name} | ${r.keys} | ` + codes.map((c) => coverage(r, c) + '%').join(' | ') + ' |'),
    '',
    `Shared code (shell/, shared/) still has ${rows.find((r) => r.id === 'shared').hard} hard-coded strings; most belong to one app family (office, biz, watermark, ...).`,
    '',
    '## Apps, by strings to translate',
    '',
    '| # | App | Id | Strings | In tables | Hard-coded | Languages at 100% |',
    '|---:|---|---|---:|---:|---:|---:|',
    ...ranked.map((r, i) => `| ${i + 1} | ${r.name} | ${r.id} | ${r.keys + r.hard} | ${r.keys} | ${r.hard} | ${codes.filter((c) => coverage(r, c) >= 100).length} of ${codes.length} |`),
    '',
    `Total: ${ranked.reduce((s, r) => s + r.keys + r.hard, 0)} strings in ${ranked.length} apps.`,
    '',
    '## Apps with tables, per language',
    '',
    '| App | ' + codes.join(' | ') + ' |',
    '|---|' + codes.map(() => '---:').join('|') + '|',
    ...ranked.filter((r) => r.keys).map((r) => `| ${r.id} | ` + codes.map((c) => coverage(r, c) + '%').join(' | ') + ' |'),
    '',
  ];
  return lines.join('\n');
}

/** The ratchet's numbers for a row: its coverage per language, in whole percent (only the languages above 0). */
export function levels(r) {
  const o = {};
  for (const c of Object.keys(r.langs)) { const v = coverage(r, c); if (v > 0) o[c] = v; }
  return o;
}
/** What a row lost against its baseline: [message]. */
export function losses(now, base) {
  return Object.entries(base || {}).filter(([c, v]) => (now[c] || 0) < v).map(([c, v]) => `${c}: ${now[c] || 0}%, was ${v}%`);
}
/** The baseline raised to now, never lowered. */
export function raise(rows, base) {
  const out = { ...base };
  for (const r of rows) {
    const now = levels(r), was = base[r.id] || {}, row = {};
    for (const c of new Set([...Object.keys(now), ...Object.keys(was)])) row[c] = Math.max(now[c] || 0, was[c] || 0);
    if (Object.keys(row).length) out[r.id] = row;
  }
  return out;
}
